def load(path):
    b = open(path, "rb").read()
    eol = "\r\n" if b"\r\n" in b else "\n"
    return io.open(path, encoding="utf-8", newline="").read(), eol


def save(path, text):
    io.open(path, "w", encoding="utf-8", newline="").write(text)


def patch(path, old_lines, new_lines, tag):
    text, eol = load(path)
    old = eol.join(old_lines)
    new = eol.join(new_lines)
    n = text.count(old)
    if n != 1:
        print("FAIL %-24s count=%d" % (tag, n))
        sys.exit(1)
    save(path, text.replace(old, new))
    print("OK   %-24s" % tag)


